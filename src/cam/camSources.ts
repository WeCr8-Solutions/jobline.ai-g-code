/**
 * CAM output integrations — pure, framework-free.
 *
 * What these integrations genuinely do (no vendor SDKs are used):
 *   1. Recognise which CAM system posted an NC program from its header.
 *   2. Read the tool list a post writes into the NC header comments.
 *   3. Read the tool table out of a setup sheet the CAM system exported
 *      (HTML, XML or CSV) and turn it into a tool library.
 *   4. Find the setup sheet that belongs to a program (same base name, in the
 *      same folder) so the two can be linked.
 *
 * What they do NOT do: talk to a running ESPRIT, Mastercam, GibbsCAM, Fusion
 * or Hexagon session, read native part files (.esp, .mcam, .vnc, .f3d
 * toolpaths), or push changes back. Each of those needs the vendor's licensed
 * API (ESPRIT KBM/COM API, Mastercam NET-Hook/C-Hook, GibbsCAM plug-in SDK,
 * the Fusion API inside Fusion) and is out of scope for a VS Code extension.
 */

