export function camSystem(id: CamSystemId): CamSystemInfo | undefined {
  return CAM_SYSTEMS.find(s => s.id === id);
}

// ── Detecting the CAM system from an NC header ───────────────────────────────

function headerComments(text: string, maxLines = 60): string[] {
  const out: string[] = [];
  const lines = text.split(/\r?\n/).slice(0, maxLines);
  for (const line of lines) {
    const paren = line.match(/\(([^)]*)\)?/g);
    if (paren) for (const p of paren) out.push(p.replace(/^\(|\)$/g, ''));
    const semi = line.indexOf(';');
    if (semi >= 0) out.push(line.slice(semi + 1));
  }
  return out;
}

export function detectCamSystem(ncText: string): CamSystemId {
  const comments = headerComments(ncText).join('\n');
  if (!comments.trim()) return 'unknown';
  for (const sys of CAM_SYSTEMS) {
    if (sys.signatures.some(re => re.test(comments))) return sys.id;
  }
  return 'unknown';
}

// ── Tool list from NC header comments ────────────────────────────────────────

/**
 * Posts commonly print the tool list as comments, for example
 *   Fusion:     (T1 D=10. CR=0. - ZMIN=-5. - FLAT END MILL)
 *   Mastercam:  ( T1 | 1/2 FLAT ENDMILL | H1 | D1 | DIA. - .5 )
 *   generic:    (T3 H3 D3 DIA 0.25 DRILL)
 * Only comment lines that begin with a T-number are read, so cutting moves and
 * notes elsewhere in the program are ignored.
 */
export function extractToolsFromNcComments(ncText: string, name = 'NC header'): ToolLibrary {
  const tools: LibraryTool[] = [];
  const warnings: string[] = [];
  const unit: LengthUnit | undefined = /\bG21\b/.test(ncText.slice(0, 4000)) ? 'mm' : /\bG20\b/.test(ncText.slice(0, 4000)) ? 'in' : undefined;
  const seen = new Set<number>();
  for (const line of ncText.split(/\r?\n/)) {
    const trimmed = line.trim();
    const m = /^(?:N\d+\s*)?\(\s*(?:TOOL\s*[-:#]?\s*)?T\s*0*(\d+)\b([^)]*)\)?\s*$/i.exec(trimmed);
    if (!m) continue;
    const number = parseInt(m[1], 10);
    if (!(number > 0) || seen.has(number)) continue;
    const rest = m[2];
    const h = /\bH\s*0*(\d+)\b/i.exec(rest);
    const dReg = /\bD\s*0*(\d+)\b(?!\s*[=.])/i.exec(rest);
    const dia = /\bD\s*=\s*(\d*\.?\d+)/i.exec(rest) ?? /\bDIA(?:METER)?\.?\s*[-=:]?\s*(\d*\.?\d+)/i.exec(rest) ?? /Ø\s*(\d*\.?\d+)/.exec(rest);
    const cr = /\bCR\s*=\s*(\d*\.?\d+)/i.exec(rest);
    // Description: the words left once the numbered fields are removed.
    const desc = rest
      .replace(/\b(D|CR|ZMIN|ZMAX|TAPER|H)\s*=?\s*-?\d*\.?\d+\.?/gi, ' ')
      .replace(/\bDIA(?:METER)?\.?\s*[-=:]?\s*\d*\.?\d+/gi, ' ')
      .replace(/\b(H|D)\s*\d+\b/gi, ' ')
      .replace(/Ø\s*\d*\.?\d+/g, ' ')
      .replace(/[|]+/g, ' ').replace(/\s-\s/g, ' ').replace(/\s+/g, ' ').trim().replace(/^[-–\s]+|[-–\s]+$/g, '');
    seen.add(number);
    const tool: LibraryTool = { number };
    if (h) tool.lengthOffset = parseInt(h[1], 10);
    if (dReg) tool.diameterOffset = parseInt(dReg[1], 10);
    if (dia) tool.diameter = parseFloat(dia[1]);
    if (cr) tool.cornerRadius = parseFloat(cr[1]);
    if (desc) tool.description = desc;
    if (unit) tool.unit = unit;
    tools.push(tool);
  }
  return buildLibrary(name, 'setup-sheet-html', tools, warnings);
}

// ── Setup sheets ─────────────────────────────────────────────────────────────

function cellText(html: string): string {
  return decodeEntities(html.replace(/<br\s*\/?>/gi, ' ').replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim();
}

/** Tables as rows of cell text. Nested tables are flattened into their own entries. */
export function htmlTables(html: string): string[][][] {
  const tables: string[][][] = [];
  const clean = html.replace(/<!--[\s\S]*?-->/g, '').replace(/<(script|style)\b[\s\S]*?<\/\1>/gi, '');
  // Innermost tables first: a table whose body holds no other <table>.
  const re = /<table\b[^>]*>((?:(?!<table\b)[\s\S])*?)<\/table>/gi;
  let rest = clean;
  for (let guard = 0; guard < 50; guard++) {
    let found = false;
    rest = rest.replace(re, (_all, body: string) => {
      found = true;
      const rows: string[][] = [];
      const rowRe = /<tr\b[^>]*>([\s\S]*?)(?=<tr\b|<\/tr>|$)/gi;
      let r: RegExpExecArray | null;
      while ((r = rowRe.exec(body))) {
        const cells: string[] = [];
        const cellRe = /<t([hd])\b([^>]*)>([\s\S]*?)(?=<t[hd]\b|<\/t[hd]>|<\/tr>|$)/gi;
        let c: RegExpExecArray | null;
        while ((c = cellRe.exec(r[1]))) {
          const span = parseInt(xmlAttributes(c[2]).colspan ?? '1', 10);
          const text = cellText(c[3]);
          cells.push(text);
          for (let k = 1; k < Math.min(span, 20); k++) cells.push('');
        }
        if (cells.length) rows.push(cells);
      }
      if (rows.length) tables.push(rows);
      return ' ';
    });
    if (!found) break;
  }
  return tables;
}

function unitHint(text: string): LengthUnit | undefined {
  const m = /\bunits?\b[^a-z]{0,6}(mm|millimet|metric|inch|inches|in\b|imperial)/i.exec(text);
  if (!m) return undefined;
  return /^(mm|millimet|metric)/i.test(m[1]) ? 'mm' : 'in';
}

/**
 * Key/value tool blocks: setup sheets that print one small table (or one list)
 * per tool, e.g. "T1 | Diameter: 10mm | Length offset: 1 | Flute length: 22".
 */
function toolsFromKeyValueBlocks(tables: string[][][], warnings: string[], unit?: LengthUnit): LibraryTool[] {
  const tools: LibraryTool[] = [];
  for (const table of tables) {
    const flat = table.flat().filter(Boolean);
    const tCell = flat.find(c => /^T\s*0*\d+\b/i.test(c) || /^tool\s*(#|no\.?|number)?\s*:?\s*T?\s*\d+\b/i.test(c));
    if (!tCell) continue;
    const tm = /T?\s*0*(\d+)\b/i.exec(tCell.replace(/^tool\s*(#|no\.?|number)?\s*:?\s*/i, ''));
    if (!tm) continue;
    const header: string[] = [];
    const values: string[] = [];
    const push = (k: string, v: string) => { header.push(k); values.push(v); };
    push('T', tm[1]);
    for (const row of table) {
      for (let i = 0; i < row.length; i++) {
        const kv = /^([A-Za-z][\w .#/-]{0,30}?)\s*[:=]\s*(.+)$/.exec(row[i]);
        if (kv && headerField(kv[1])) push(kv[1], kv[2]);
        else if (i + 1 < row.length && headerField(row[i].replace(/:$/, '')) && row[i + 1]) { push(row[i].replace(/:$/, ''), row[i + 1]); i++; }
      }
    }
    // A key/value block needs more than just "T1" to be worth keeping.
    if (header.length < 2) continue;
    tools.push(...toolsFromTable(header, [values], 'setup sheet', warnings, unit));
  }
  return tools;
}

export function parseSetupSheetHtml(html: string, name = 'setup-sheet.html'): ToolLibrary {
  const warnings: string[] = [];
  const unit = unitHint(cellText(html));
  const tables = htmlTables(html);
  let tools: LibraryTool[] = [];
  // Column tables first (one row per tool) — Mastercam, ESPRIT, GibbsCAM style.
  for (const table of tables) {
    const headerIndex = table.findIndex(row => row.map(headerField).includes('number') && row.filter(c => headerField(c)).length >= 2);
    if (headerIndex < 0) continue;
    tools.push(...toolsFromTable(table[headerIndex], table.slice(headerIndex + 1), name, warnings, unit));
  }
  if (!tools.length) tools = toolsFromKeyValueBlocks(tables, warnings, unit);
  if (!tools.length) {
    // Last resort: a sheet that prints the post's tool comments verbatim.
    const fromComments = extractToolsFromNcComments(cellText(html.replace(/<\/(p|div|li|tr|br)>/gi, '\n')).replace(/\s*(\(T\d)/g, '\n$1'), name);
    tools = fromComments.tools;
  }
  if (!tools.length) throw new Error(`${name}: no tool table found. Expected a table with a tool-number column (T, Tool #, Number).`);
  return buildLibrary(name, 'setup-sheet-html', tools, warnings);
}

/** Generic XML tool list: any repeated element whose name contains "tool". */
export function parseSetupSheetXml(xml: string, name = 'tools.xml'): ToolLibrary {
  if (/<tool-library\b/i.test(xml)) return parseHsmLibrary(xml, name);
  const warnings: string[] = [];
  const unit = unitHint(xml.replace(/<[^>]+>/g, ' ')) ?? unitFromAttr(xml);
  const tools: LibraryTool[] = [];
  const visit = (fragment: string, depth: number) => {
    if (depth > 6) return;
    const re = /<([\w:.-]*tool[\w:.-]*)\b([^>]*?)(?:\/>|>([\s\S]*?)<\/\1\s*>)/gi;
    let m: RegExpExecArray | null;
    while ((m = re.exec(fragment))) {
      const inner = m[3] ?? '';
      // Recurse into containers (<Tools><Tool>…</Tool></Tools>): a child whose
      // name contains "tool" and that itself holds elements or attributes.
      // Leaf fields such as <ToolNumber>1</ToolNumber> don't count.
      if (/<([\w:.-]*tool[\w:.-]*)\b[^>]*>\s*</i.test(inner) || /<[\w:.-]*tool[\w:.-]*\b[^>]*=[^>]*\/>/i.test(inner)) {
        visit(inner, depth + 1);
        continue;
      }
      const header: string[] = [];
      const values: string[] = [];
      for (const [k, v] of Object.entries(xmlAttributes(m[2]))) { header.push(k); values.push(v); }
      const childRe = /<([\w:.-]+)\b([^>]*)>([^<]*)<\/\1>/g;
      let c: RegExpExecArray | null;
      while ((c = childRe.exec(inner))) {
        header.push(c[1]); values.push(decodeEntities(c[3]).trim());
        const unitAttr = xmlAttributes(c[2]).unit ?? xmlAttributes(c[2]).units;
        if (unitAttr && !header.includes('unit')) { header.push('unit'); values.push(unitAttr); }
      }
      const fields = header.map(headerField);
      if (!fields.includes('number')) continue;
      tools.push(...toolsFromTable(header, [values], name, warnings, unit));
    }
  };
  visit(xml, 0);
  if (!tools.length) throw new Error(`${name}: no tool elements with a tool number found.`);
  return buildLibrary(name, 'setup-sheet-xml', tools, warnings);
}

function unitFromAttr(xml: string): LengthUnit | undefined {
  const m = /\bunits?\s*=\s*["'](mm|millimeters?|metric|inch|inches|in)["']/i.exec(xml);
  if (!m) return undefined;
  return /^(mm|millimet|metric)/i.test(m[1]) ? 'mm' : 'in';
}

/** Read any supported setup sheet / tool list by extension and content. */
export function parseSetupSheet(name: string, bytes: Uint8Array): ToolLibrary {
  const text = decodeText(bytes);
  const ext = (/\.([a-z0-9]+)$/i.exec(name)?.[1] ?? '').toLowerCase();
  const head = text.trimStart().slice(0, 300).toLowerCase();
  if (ext === 'csv' || ext === 'tsv') return parseToolCsv(text, name);
  if (ext === 'hsmlib') return parseHsmLibrary(text, name);
  if (ext === 'htm' || ext === 'html' || head.startsWith('<!doctype html') || head.startsWith('<html')) return parseSetupSheetHtml(text, name);
  if (ext === 'xml' || head.startsWith('<?xml') || head.startsWith('<')) {
    // Some "XML" setup sheets are XHTML.
    if (/<table\b/i.test(text) && !/<[\w:.-]*tool[\w:.-]*\b[^>]*>\s*<(number|toolnumber)/i.test(text)) {
      try { return parseSetupSheetHtml(text, name); } catch { /* fall through to XML */ }
    }
    return parseSetupSheetXml(text, name);
  }
  if (ext === 'txt') return parseToolCsv(text, name);
  throw new Error(`${name}: unsupported setup sheet. Use HTML, XML or CSV.`);
}

// ── Linking programs and setup sheets ────────────────────────────────────────

export const NC_EXTENSIONS = ['nc', 'tap', 'ngc', 'cnc', 'gcode', 'g', 'eia', 'iso', 'min', 'mpf', 'spf', 'prg', 'h', 'i', 'fgc', 'ncc', 'nc1', 'ptp', 'dnc', 'txt'];
export const SETUP_SHEET_EXTENSIONS = ['html', 'htm', 'xml', 'csv'];

function stem(name: string): string {
  const base = name.split(/[\\/]/).pop() ?? name;
  return base.replace(/\.[^.]+$/, '').toLowerCase();
}

/**
 * Setup sheets in the same folder that belong to `ncName`, best match first:
 *   1234.html, 1234_setup.html, 1234-setupsheet.xml, 1234 Tool List.csv,
 *   Setup Sheet 1234.htm. A lone setup sheet in the folder is offered last.
 */
export function findSetupSheetCandidates(ncName: string, siblingNames: string[]): string[] {
  const s = stem(ncName);
  if (!s) return [];
  const sheets = siblingNames.filter(n => SETUP_SHEET_EXTENSIONS.includes((/\.([a-z0-9]+)$/i.exec(n)?.[1] ?? '').toLowerCase()));
  const scored: Array<[string, number]> = [];
  const escaped = s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  for (const n of sheets) {
    const t = stem(n);
    let score = 0;
    if (t === s) score = 100;
    else if (new RegExp(`^${escaped}[\\s_.-]*(setup|tool|sheet|tools|setupsheet|toollist)`, 'i').test(t)) score = 90;
    else if (new RegExp(`(setup|tool|sheet)[\\s_.-]*${escaped}$`, 'i').test(t)) score = 80;
    else if (t.startsWith(s + '_') || t.startsWith(s + '-') || t.startsWith(s + ' ') || t.startsWith(s + '.')) score = 60;
    if (score) scored.push([n, score + (/\.html?$/i.test(n) ? 2 : /\.xml$/i.test(n) ? 1 : 0)]);
  }
  if (!scored.length) {
    const generic = sheets.filter(n => /setup|tool/i.test(n));
    if (generic.length === 1) scored.push([generic[0], 10]);
  }
  return scored.sort((a, b) => b[1] - a[1]).map(([n]) => n);
}

export function isNcFileName(name: string): boolean {
  const ext = (/\.([a-z0-9]+)$/i.exec(name)?.[1] ?? '').toLowerCase();
  return NC_EXTENSIONS.includes(ext) && ext !== 'txt';
}

